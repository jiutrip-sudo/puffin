const TW_REPLACEMENTS = [
  ...CN_TERMS.map(([tw, cn]) => [cn, tw] as const),
  ...TW_EXTRA_TERMS,
]
  .filter(([from, to]) => from !== to)
  .sort((a, b) => b[0].length - a[0].length);

export function normalizeContentForTaiwan(text: string): string {
  if (!text) return text;

  let out = cnToTwConverter(text);
  out = normalizePlaceAliases(out);

  for (const [from, to] of TW_REPLACEMENTS) {
    out = out.split(from).join(to);
  }

  // 地名 alias 展開後可能產生的重複後綴
  out = out.replace(/辛格維利爾國家公園國家公園/g, "辛格維利爾國家公園");

  return out;
}
